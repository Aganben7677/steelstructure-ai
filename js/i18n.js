let currentLang = localStorage.getItem("site-lang") || "en";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("site-lang", lang);
  applyTranslations();
  updateLangButton();
  window.dispatchEvent(new CustomEvent("site-language-change", { detail: { lang } }));
}

function t(key) {
  return i18n[currentLang][key] || i18n.en[key] || key;
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);

    if (el.tagName === "INPUT") {
      el.placeholder = val;
      return;
    }

    if ((el.tagName === "A" || el.tagName === "BUTTON") && el.querySelector("*")) {
      return;
    }

    el.textContent = val;
  });

  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
}

function updateLangButton() {
  const btn = document.getElementById("lang-toggle");
  if (!btn) return;

  btn.textContent = currentLang === "en" ? i18n.en.lang_cn : i18n.en.lang_en;
  btn.title = currentLang === "en" ? "Switch to Chinese" : "Switch to English";
}

function toggleLanguage() {
  setLanguage(currentLang === "en" ? "zh" : "en");
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  updateLangButton();
});
